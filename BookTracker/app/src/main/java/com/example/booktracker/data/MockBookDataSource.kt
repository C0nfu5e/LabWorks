    suspend fun getBookById(bookId: Long, simulateError: Boolean = false): Book {
        delay(500)
        if (simulateError) {
            throw IllegalStateException("Не удалось загрузить данные о книге (ошибка сети)")
        }
        return books.find { it.id == bookId }
            ?: throw NoSuchElementException("Книга с id=$bookId не найдена")
    }

    fun isFavorite(bookId: Long): Boolean = bookId in _favoriteIds.value

    suspend fun toggleFavorite(bookId: Long): Boolean {
        delay(200)
        var nowFavorite = false
        _favoriteIds.update { current ->
            if (bookId in current) {
                nowFavorite = false
                current - bookId
            } else {
                nowFavorite = true
                current + bookId
            }
        }
        return nowFavorite
    }
